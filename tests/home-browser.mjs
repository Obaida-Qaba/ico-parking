import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
import {observeMap} from './observe-map.mjs';
mkdirSync('test-results',{recursive:true});
const base=(process.env.PORTWAY_BASE_URL||'http://127.0.0.1:4173').replace(/\/$/,'');
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
await observeMap(context,'__homeMap');
await context.addInitScript(()=>{
 window.__homeStarts=0;window.__homeStops=0;
 navigator.geolocation.watchPosition=ok=>{window.__homeStarts++;window.__homeFix=ok;ok({timestamp:Date.now(),coords:{latitude:51.30217,longitude:3.22683,accuracy:4,speed:0}});return 53;};
 navigator.geolocation.clearWatch=()=>window.__homeStops++;
});
const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto(base);await page.locator('.map-card').last().waitFor({state:'attached'});
 assert.equal(await page.evaluate(()=>window.__homeStarts),1,'home starts live location without a start button');
 await page.locator('.gps-dot').waitFor();
 assert.equal(await page.locator('#terminal-filter').inputValue(),'auto');
 await page.waitForFunction(()=>/Bastenaken/.test(document.getElementById('location-context').textContent));
 const layout=await page.evaluate(()=>{const map=document.getElementById('map').getBoundingClientRect(),search=document.getElementById('destination').getBoundingClientRect();return {mapArea:map.width*map.height/(innerWidth*innerHeight),searchTop:search.top,overflow:document.documentElement.scrollWidth>innerWidth};});
 assert.ok(layout.mapArea>.95,'location map fills the home screen');assert.ok(layout.searchTop<80,'search is at the top');assert.equal(layout.overflow,false);
 assert.equal(await page.locator('.leaflet-image-layer').count(),0,'home uses geographic GPS view');
 await page.screenshot({path:'test-results/mobile-map-first-home.png',fullPage:true});
 const move=async(lat,lon)=>page.evaluate(({lat,lon})=>window.__homeFix({timestamp:Date.now(),coords:{latitude:lat,longitude:lon,accuracy:4,speed:0}}),{lat,lon});
 await move(51.301,3.242);
 await page.waitForFunction(()=>/Toyota/.test(document.getElementById('location-context').textContent));
 assert.equal(await page.locator('[data-map="toyota"]').getAttribute('aria-pressed'),'true','nearby Toyota plan is selected');
 await page.locator('#destination').fill('A');await page.locator('.result-row').first().waitFor();
 assert.equal(await page.locator('.result-row').first().getAttribute('data-terminal'),'toyota','Toyota parkings come first at Toyota');
 assert.equal(await page.locator('.result-row').first().getAttribute('data-preferred'),'true');
 await page.waitForFunction(()=>Number(getComputedStyle(document.getElementById('search-results')).opacity)>.99);
 assert.ok(await page.locator('.result-row[data-preferred="false"]').count()>0,'other terminals remain searchable');
 await page.screenshot({path:'test-results/mobile-toyota-first-search.png',fullPage:true});
 await page.locator('.result-row').first().click();
 assert.equal(await page.locator('.destination-code').innerText(),'A01');
 assert.equal(await page.locator('.leaflet-image-layer').count(),0,'choosing a parking keeps the GPS map');
 await page.locator('#view-plan-button').click();await page.locator('.leaflet-image-layer').waitFor();
 await page.locator('#clear-destination').click();await page.locator('.gps-dot').waitFor();
 assert.equal(await page.locator('.leaflet-image-layer').count(),0,'closing the plan preview returns to location');
 await page.locator('#search-settings').evaluate(el=>el.open=true);
 await page.locator('#terminal-filter').selectOption('bastenaken');
 await move(51.29689,3.24508);
 assert.equal(await page.locator('#location-context').innerText(),'Bastenaken','manual area survives location changes');
 await page.locator('#destination').fill('HC');await page.locator('.result-row').first().waitFor();
 assert.equal(await page.locator('.result-row').first().getAttribute('data-terminal'),'bastenaken');
 assert.equal(await page.locator('.result-row').first().getAttribute('data-preferred'),'false','manual selection overrides automatic priority');
 await page.locator('#search-settings').evaluate(el=>el.open=true);await page.locator('#terminal-filter').selectOption('auto');
 assert.match(await page.locator('#location-context').innerText(),/Hanze/);
 assert.equal(await page.locator('[data-map="south"]').getAttribute('aria-pressed'),'true','automatic context restores the current regional plan immediately');
 await page.locator('#destination').fill('HC1');await page.locator('.find-button').click();
 assert.equal(await page.locator('.destination-code').innerText(),'HC1','exact parking elsewhere is found when the nearby terminal has no match');
 await move(51.3019,3.2270544);await page.locator('#route-button').click();await page.locator('.road-route').waitFor();
 assert.equal(await page.locator('#destination').isVisible(),true,'search stays reachable while navigating');
 assert.equal(await page.evaluate(()=>window.__homeStarts),1,'search and plan previews do not restart GPS');
 assert.equal(await page.evaluate(()=>window.__homeStops),0);
 await page.locator('#stop-navigation').click();await page.locator('#clear-destination').click();
 for(const [lat,lon,name] of [[51.326,3.213,'Noordelijke'],[51.317,3.2105,'Nissan'],[50.85,4.35,'All terminals']]){
  await move(lat,lon);
  assert.match(await page.locator('#location-context').innerText(),new RegExp(name,'i'),'context follows reliable locations without choosing a terminal outside the port');
 }
 await page.waitForFunction(()=>navigator.serviceWorker.controller&&document.getElementById('offline-status').textContent==='Maps saved offline');
 await context.setOffline(true);await page.goto(base);await page.locator('.gps-dot').waitFor();
 assert.match(await page.locator('#location-context').innerText(),/Bastenaken/,'terminal detection works offline');
 const denied=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await denied.addInitScript(()=>{navigator.geolocation.watchPosition=(ok,fail)=>{fail({code:1});return 9;};navigator.geolocation.clearWatch=()=>{};});
 const deniedPage=await denied.newPage();deniedPage.on('pageerror',e=>errors.push(e.message));
 await deniedPage.goto(base);await deniedPage.locator('.map-card').last().waitFor({state:'attached'});
 assert.equal(await deniedPage.locator('#location-context').innerText(),'Location off');
 assert.equal(await deniedPage.locator('dialog[open]').count(),0,'location denial does not block search');
 assert.equal(await deniedPage.locator('#gps-status-alert').isVisible(),false,'initial denial stays compact');
 await deniedPage.locator('#destination').fill('Toyota A01');await deniedPage.locator('.find-button').click();
 assert.equal(await deniedPage.locator('.destination-code').innerText(),'A01','manual search works without location permission');
 assert.deepEqual(errors,[]);
 console.log('PASS map-first home: automatic GPS, Toyota-first results with fallback, region changes, manual override, plan preview, continuous tracking, denied location and offline');
}finally{await browser.close();}
