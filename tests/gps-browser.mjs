import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {readFileSync,mkdirSync} from 'node:fs';
import {distanceMetres,buildGraph,routeRoads} from '../public/navigation.mjs';
mkdirSync('test-results',{recursive:true});
const data=JSON.parse(readFileSync('public/roads.json','utf8'));
const graph=buildGraph(data);
const road=graph.segments.find(s=>s.distance>100&&s.pa[0]>51.29&&s.pa[0]<51.31&&s.pa[1]>3.22&&s.pa[1]<3.25&&s.oneway!==-1);
assert.ok(road,'real mapped terminal road fixture');
const at=t=>[road.pa[0]+t*(road.pb[0]-road.pa[0]),road.pa[1]+t*(road.pb[1]-road.pa[1])];
const start=at(.1),target=at(.9),moved=at(.4);
const base=(process.env.PORTWAY_BASE_URL||'http://127.0.0.1:4173').replace(/\/$/,'');
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
const page=await context.newPage(),errors=[];
page.on('pageerror',e=>errors.push(e.stack));
await context.addInitScript(({start,target})=>{
  window.__clearCount=0;
  navigator.geolocation.watchPosition=(ok,fail)=>{
    window.__gpsUpdate=ok;
    ok({timestamp:Date.now(),coords:{latitude:start[0],longitude:start[1],accuracy:6,heading:40,speed:3}});
    return 7;
  };
  navigator.geolocation.clearWatch=()=>window.__clearCount++;
  navigator.geolocation.getCurrentPosition=ok=>ok({timestamp:Date.now(),coords:{latitude:target[0],longitude:target[1],accuracy:6}});
},{start,target});
try{
  await page.goto(base+'/?map=south&parking=H61&line=15');
  await page.locator('.destination-code').waitFor();
  await page.locator('#route-button').click();
  assert.match(await page.locator('#dialog-content').innerText(),/Save its real position once/);
  assert.equal(await page.locator('.road-route').count(),0);
  await page.locator('#capture-parking').click();
  await page.locator('.road-route').waitFor();
  assert.match(await page.locator('#gps-text').innerText(),/GPS live/);
  assert.match(await page.locator('#navigation-destination').innerText(),/H61.*15/);
  const before=parseFloat(await page.locator('#navigation-distance').innerText());
  const expected=routeRoads(graph,start,target);
  assert.ok(expected.available);
  assert.ok(Math.abs(before-expected.distance)<2);
  assert.equal(await page.locator('.gps-dot').count(),1);
  const pin=await page.evaluate(()=>JSON.parse(localStorage.getItem('portway-gps-pins'))['south:H61:15']);
  assert.ok(distanceMetres([pin.lat,pin.lon],target)<.1);
  await page.waitForTimeout(2100);
  await page.evaluate(p=>window.__gpsUpdate({timestamp:Date.now(),coords:{latitude:p[0],longitude:p[1],accuracy:5,heading:45,speed:4}}),moved);
  await page.waitForFunction(before=>parseFloat(document.getElementById('navigation-distance').textContent)<before,before);
  await page.screenshot({path:'test-results/mobile-live-gps-simulation.png',fullPage:true});
  await page.evaluate(p=>window.__gpsUpdate({timestamp:Date.now(),coords:{latitude:p[0],longitude:p[1],accuracy:90}}),moved);
  assert.match(await page.locator('#navigation-instruction').innerText(),/more accurate GPS/);
  assert.equal(await page.locator('.road-route').count(),0);
  await page.locator('#gps-toggle').click();
  assert.ok(await page.evaluate(()=>window.__clearCount)>0);
  assert.equal(await page.locator('#navigation-panel').isVisible(),false);
  await page.waitForFunction(()=>document.getElementById('offline-status').textContent==='Maps saved offline');
  await context.setOffline(true);
  await page.reload();await page.locator('.destination-code').waitFor();
  assert.match(await page.locator('#route-button').innerText(),/Start GPS route/);
  await page.locator('#route-button').click();
  await page.locator('.road-route').waitFor();
  assert.match(await page.locator('#gps-text').innerText(),/GPS live/);
  assert.ok((await page.locator('#map').boundingBox()).height>=300);
  assert.deepEqual(errors,[]);
  console.log('PASS GPS: on-site coordinate capture, live watch, road-matched route, distance updates, heading, low-accuracy pause, stop tracking, saved destination and offline road routing');
}finally{await browser.close();}
